def render_md(it):
    lines = []
    lines.append("# 访谈记录 %02d · %s（%s）" % (it["no"], it["name"], it["role"].split("（")[0]))
    lines.append("")
    lines.append("| 项 | 内容 |")
    lines.append("|---|---|")
    lines.append("| 访谈编号 | %s |" % it["id"])
    lines.append("| 时间 | %s |" % it["date"])
    lines.append("| 地点 | %s |" % it["place"])
    lines.append("| 受访人 | %s，%s |" % (it["name"], it["role"]))
    lines.append("| 访谈人 | 项目 FDE（业务挖掘阶段） |")
    lines.append("| 时长 | %d 分钟 |" % it["duration"])
    lines.append("| 关联证据 | %s |" % it["evidence"])
    lines.append("| 记录方式 | 现场速记 + 录音转写，受访人已确认关键原话 |")
    lines.append("")
    lines.append("## 访谈背景")
    lines.append("")
    lines.append(it["background"])
    lines.append("")
    lines.append("## 问答摘录")
    lines.append("")
    for q, a in it["qa"]:
        lines.append("**问：** %s" % q)
        lines.append("")
        lines.append("**答：** %s" % a)
        lines.append("")
    lines.append("## 现场观察")
    lines.append("")
    for o in it["observe"]:
        lines.append("- %s" % o)
    lines.append("")
    lines.append("## 本次访谈的结论")
    lines.append("")
    for c in it["conclusion"]:
        lines.append("- %s" % c)
    lines.append("")
    lines.append("> 本记录仅用于本项目合成场景，不包含顾客个人信息；引用原话已由受访人确认，"
                 "涉及金额与工时的表述为受访人自报，未做单据核对。")
    lines.append("")
    return "\n".join(lines)


