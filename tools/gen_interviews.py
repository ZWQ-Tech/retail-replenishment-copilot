    for it in INTERVIEWS:
        fn = "%02d-%s-%s.md" % (it["no"], it["name"], it["role"].split("（")[0])
        with open(os.path.join(OUT_DIR, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(render_md(it))

    with open(os.path.join(OUT_DIR, "00-汇总.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(render_summary())

    with open(os.path.join(OUT_DIR, "访谈记录.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["访谈编号", "日期时间", "受访人", "角色", "时长(分钟)", "序号", "问题", "回答", "关联证据"])
        for it in INTERVIEWS:
            for i, (q, a) in enumerate(it["qa"], 1):
                w.writerow([it["id"], it["date"], it["name"], it["role"], it["duration"], i, q, a, it["evidence"]])

